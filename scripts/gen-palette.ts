// Writes src/styles/palette.generated.css from src/design/palette.ts and enforces the contrast floors.
import { writeFile } from "node:fs/promises";
import { pairs, palette, ratio, type Token } from "../src/design/palette";

let failed = 0;
for (const [fg, bg, min, modes = [0, 1] as (0 | 1)[]] of pairs) {
  for (const mode of modes) {
    const r = ratio(fg, bg, mode);
    if (r < min) {
      console.error(`contrast ${fg} on ${bg} (${mode ? "dark" : "light"}): ${r.toFixed(2)} < ${min}`);
      failed++;
    }
  }
}
if (failed) process.exit(1);

// Custom properties are declared per scope, not with light-dark(): Chrome resolves light-dark() where a custom
// property is declared, so a nested dark band would keep the light values.
const keys = Object.keys(palette) as Token[];
const decl = (mode: 0 | 1, indent = "  ") => keys.map((k) => `${indent}--${k}: ${palette[k][mode]};`).join("\n");
await writeFile(
  "src/styles/palette.generated.css",
  `/* Generated by scripts/gen-palette.ts from src/design/palette.ts. Do not edit. */
:root {
${decl(0)}
  color-scheme: light;
}
@media (prefers-color-scheme: dark) {
  :root:not([data-mode="light"]) {
${decl(1, "    ")}
    color-scheme: dark;
  }
}
:root[data-mode="dark"] {
${decl(1)}
  color-scheme: dark;
}
.dark-band {
${decl(1)}
  color-scheme: dark;
}
`,
);
console.log(`palette ok (${pairs.reduce((n, p) => n + (p[3]?.length ?? 2), 0)} contrast checks)`);
